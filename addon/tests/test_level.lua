H.test("level: PLAYER_LEVEL_UP posts with 0.5 s screenshot delay, priority", function()
  local ns = H.Boot()
  W.Fire("PLAYER_LEVEL_UP", 21)
  local ev = H.EventsOfType(ns, "level")
  H.eq(#ev, 1)
  H.contains(ev[1].raw, '"level":21')
  H.contains(ev[1].raw, '"zone":"Elwynn Forest"')
  H.ok(ns.Screenshot.queue[1].priority)
  W.Advance(0.4)
  H.eq(#W.screenshots, 0)
  W.Advance(0.2)
  H.eq(#W.screenshots, 1)
end)
