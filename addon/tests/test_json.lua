H.test("json: scalars, escaping and sorted keys", function()
  local ns = H.Boot()
  local J = ns.Json
  H.eq(J.Encode(1), "1")
  H.eq(J.Encode(1.5), "1.5")
  H.eq(J.Encode(true), "true")
  H.eq(J.Encode("a\"b\\c\n"), '"a\\"b\\\\c\\n"')
  H.eq(J.Encode("\1"), '"\\u0001"')
  H.eq(J.Encode({ b = 1, a = "x" }), '{"a":"x","b":1}')
  H.eq(J.Encode({ 1, 2, 3 }), "[1,2,3]")
  H.eq(J.Encode({}), "{}")
  H.eq(J.Encode({ a = { b = { false } } }), '{"a":{"b":[false]}}')
  H.eq(J.Encode("Navtök"), '"Navtök"', "utf-8 passes through")
end)
