-- fixture_common.lua: the fixed event used for the encoder<->decoder fixture.
-- The Go test (companion/internal/barcode/fixture_test.go) reads fixtures/barcode_v1.txt,
-- re-encodes the payload with the Go encoder, compares grids and decodes a rendered JPEG.
FIXTURE_EVENT = {
  type = "loot", test = false, ts = 1764160000, seq = 42,
  char = "Navtök", classId = 8, level = 60,
  data = { itemId = 19019, quality = 5, count = 1, item = "Thunderfury, Blessed Blade of the Windseeker" },
}

function FixtureText(ns)
  local B = ns.Barcode
  local payload = B.EncodePayload(FIXTURE_EVENT)
  local frame = B.BuildFrame(payload)
  local grid = B.BuildGrid(frame)
  local hex = {}
  for i = 1, #payload do hex[#hex + 1] = string.format("%02x", payload:byte(i)) end
  local fhex = {}
  for i = 1, #frame do fhex[#fhex + 1] = string.format("%02x", frame[i]) end
  local lines = {
    "# NAVTOK barcode fixture (generated by addon/tests/gen_fixture.lua - do not edit)",
    "version: " .. B.VERSION,
    "payload_hex: " .. table.concat(hex),
    "frame_hex: " .. table.concat(fhex),
    "rows: " .. B.ROWS,
    "cols: " .. B.COLS,
    "quiet: " .. B.QUIET,
    "grid:",
  }
  for r = 0, B.ROWS - 1 do
    local row = {}
    for c = 0, B.COLS - 1 do row[#row + 1] = tostring(grid[r * B.COLS + c + 1]) end
    lines[#lines + 1] = table.concat(row)
  end
  return table.concat(lines, "\n") .. "\n"
end
