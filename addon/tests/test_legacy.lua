H.test("legacy: stub posts system messages matching legacyPatterns, deduped", function()
  local ns = H.Boot()
  W.Fire("CHAT_MSG_SYSTEM", "You have completed the Legacy challenge: Explorer!")
  W.Fire("CHAT_MSG_SYSTEM", "Legacy challenge complete: |cffffd000Explorer|r")
  W.Fire("CHAT_MSG_SYSTEM", "Legacy challenge complete: |cffffd000Explorer|r")
  W.Fire("CHAT_MSG_SYSTEM", "You are now AFK.")
  local ev = H.EventsOfType(ns, "legacy")
  H.eq(#ev, 2)
  H.contains(ev[2].raw, '"text":"Legacy challenge complete: Explorer"')
end)
