local function enter(name, itype, mapId)
  W.instance = name and { name = name, type = itype or "party", mapId = mapId } or nil
  W.Fire("PLAYER_ENTERING_WORLD", false, false)
end

H.test("dungeon: known final boss posts right away; no summary on leaving", function()
  local ns = H.Boot()
  enter("Deadmines", "party", 36)
  W.Fire("ENCOUNTER_END", 2741, "Rhahk'Zor", 0, 5, 1)
  W.Advance(60)
  W.Fire("ENCOUNTER_END", 2747, "Edwin VanCleef", 0, 5, 1)
  local ev = H.EventsOfType(ns, "dungeon")
  H.eq(#ev, 2, "candidate for Rhahk'Zor + final")
  H.contains(ev[1].raw, '"candidate":true')
  H.contains(ev[2].raw, '"instance":"Deadmines"')
  H.contains(ev[2].raw, '"bosses":2')
  H.ok(not ev[2].raw:find('"candidate"'), "final is a normal post")
  enter(nil)
  H.eq(#H.EventsOfType(ns, "dungeon"), 2, "no summary after a known final")
end)

H.test("dungeon: unknown instance -> candidate per boss, one summary on leaving with last shot", function()
  local ns = H.Boot()
  enter("Blackmaw Hold", "party", 2974)
  W.Fire("ENCOUNTER_END", 3315, "Withermaw", 0, 5, 1)
  W.Advance(120)
  W.Fire("ENCOUNTER_END", 3316, "Impaan the Imprisoner", 0, 5, 0) -- wipe: ignored
  W.Fire("ENCOUNTER_END", 3316, "Impaan the Imprisoner", 0, 5, 1)
  local cands = H.EventsOfType(ns, "dungeon")
  H.eq(#cands, 2)
  local lastSeq = cands[2].raw:match('"seq":(%d+)')
  W.Advance(5)
  enter(nil) -- zone out
  local ev = H.EventsOfType(ns, "dungeon")
  H.eq(#ev, 3)
  local s = ev[3].raw
  H.ok(not s:find('"candidate"'))
  H.contains(s, '"shotSeq":' .. lastSeq)
  H.contains(s, '"bosses":2')
  H.contains(s, '"instance":"Blackmaw Hold"')
  H.contains(s, '"encounter":"Impaan the Imprisoner"')
  enter(nil)
  H.eq(#H.EventsOfType(ns, "dungeon"), 3, "only once")
end)

H.test("dungeon: run survives /reload inside; no kills -> no summary", function()
  local ns = H.Boot()
  enter("The Drowned City", "party", 2970)
  W.Fire("ENCOUNTER_END", 3474, "Zul'Alai", 0, 5, 1)
  local ns2 = H.Boot({ db = NavtokDiscordDB, setup = function(w) w.instance = { name = "The Drowned City", type = "party", mapId = 2970 } end })
  H.ok(ns2.char.run and ns2.char.run.bosses == 1, "run kept")
  enter(nil)
  H.eq(#H.EventsOfType(ns2, "dungeon"), 2, "candidate + summary")
  local ns3 = H.Boot()
  enter("Alcaz Prison", "party", 2994)
  enter(nil)
  H.eq(#H.EventsOfType(ns3, "dungeon"), 0)
end)

H.test("dungeon: raid with optional bosses skipped -> summary covers it", function()
  local ns = H.Boot()
  enter("Nightmare Grove", "raid", 2832)
  W.Fire("ENCOUNTER_END", 9001, "Some New Raid Boss", 0, 20, 1)
  enter("Ashenvale") -- left (not an instance)
  local ev = H.EventsOfType(ns, "dungeon")
  H.eq(#ev, 2)
  H.contains(ev[2].raw, '"bosses":1')
end)

H.test("dungeon: unknown id but known final name still posts (fallback)", function()
  local ns = H.Boot()
  W.Fire("ENCOUNTER_END", 99999, "Edwin VanCleef", 1, 5, 1)
  local ev = H.EventsOfType(ns, "dungeon")
  H.eq(#ev, 1)
  H.contains(ev[1].raw, '"instance":"Deadmines"')
end)
