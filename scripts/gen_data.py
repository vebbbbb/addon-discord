#!/usr/bin/env python3
"""Regenerates addon/NavtokDiscord/Data/Dungeons.lua and Data/Legacy.lua from WoW Forever's
client database (DB2 tables served as CSV by https://wago.tools).

    python3 scripts/gen_data.py                 # newest 1.60.x build on wago.tools
    python3 scripts/gen_data.py 1.60.1.71139    # a specific build

Run it after a Forever patch, then `luajit addon/tests/run.lua`.
"""
import csv
import io
import re
import sys
import urllib.request

WAGO = "https://wago.tools"
ROOT = __file__.rsplit("/scripts/", 1)[0]


def get(url):
    req = urllib.request.Request(url, headers={"User-Agent": "navtok-gen-data"})
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.read().decode("utf-8")


def table(name, build):
    return list(csv.DictReader(io.StringIO(get(f"{WAGO}/db2/{name}/csv?build={build}"))))


def latest_build():
    page = get(f"{WAGO}/db2/DungeonEncounter")
    builds = set(re.findall(r"1\.60\.\d+\.\d+", page))
    if not builds:
        sys.exit("no 1.60.x build found on wago.tools")
    return max(builds, key=lambda b: tuple(int(x) for x in b.split(".")))


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


# ---------------------------------------------------------------------------------------------
# Dungeons: final boss per instance (or per wing). Encounter ids come from the game data.
# Only well-known final bosses are listed. Instances without an entry (e.g. new Forever
# dungeons) are handled dynamically by the addon: a summary post when you leave, using the
# screenshot of the last boss kill (raids: the last boss of the raid lockout).
# ---------------------------------------------------------------------------------------------
WINGS = {  # map id -> [(final boss name, display name)]
    "189": [("Bloodmage Thalnos", "Scarlet Monastery: Graveyard"), ("Arcanist Doan", "Scarlet Monastery: Library"),
            ("Herod", "Scarlet Monastery: Armory"), ("High Inquisitor Whitemane", "Scarlet Monastery: Cathedral")],
    "229": [("Overlord Wyrmthalak", "Lower Blackrock Spire"), ("General Drakkisath", "Upper Blackrock Spire")],
    "329": [("Balnazzar", "Stratholme: Live"), ("Baron Rivendare", "Stratholme: Undead")],
    "429": [("Alzzin the Wildshaper", "Dire Maul: East"), ("Prince Tortheldrin", "Dire Maul: West"),
            ("King Gordok", "Dire Maul: North")],
}
KNOWN_FINAL = {  # classic instances whose final boss is well known (not always the highest order)
    "33": "Archmage Arugal", "34": "Bazil Thredd", "36": "Edwin VanCleef", "43": "Mutanus the Devourer",
    "47": "Charlga Razorflank", "48": "Aku'mai", "70": "Archaedas", "90": "Mekgineer Thermaplugg",
    "109": "Shade of Eranikus", "129": "Amnennar the Coldbringer", "209": "Chief Ukorz Sandscalp",
    "230": "Emperor Dagran Thaurissan", "249": "Onyxia", "289": "Darkmaster Gandling", "309": "Hakkar",
    "349": "Princess Theradras", "389": "Bazzalan", "409": "Ragnaros", "469": "Nefarian",
    "509": "Ossirian the Unscarred", "531": "C'thun", "533": "Kel'Thuzad",
}
ALL_BOSSES = {"2832"}            # Nightmare Grove: the four dragons can die in any order - post each
SKIP_MAPS = {"0", "13", "2720", "2921"}  # world map entry, test dungeons, single event encounter


def gen_dungeons(build):
    maps = {r["ID"]: r for r in table("Map", build)}
    by_map = {}
    for e in table("DungeonEncounter", build):
        by_map.setdefault(e["MapID"], []).append(e)
    entries = []  # (id, boss, instance, kind, known)
    for mid, encs in sorted(by_map.items(), key=lambda x: int(x[0])):
        m = maps.get(mid)
        if mid in SKIP_MAPS or not m or m.get("InstanceType") not in ("1", "2"):
            continue
        kind = "raid" if m["InstanceType"] == "2" else "dungeon"
        name = m["MapName_lang"]
        if mid in WINGS:
            for boss, inst in WINGS[mid]:
                for e in encs:
                    if e["Name_lang"] == boss:
                        entries.append((e["ID"], boss, inst, kind, True))
        elif mid in KNOWN_FINAL:
            for e in encs:
                if e["Name_lang"].lower() == KNOWN_FINAL[mid].lower():
                    entries.append((e["ID"], e["Name_lang"], name, kind, True))
        elif mid in ALL_BOSSES:
            for e in encs:
                entries.append((e["ID"], e["Name_lang"], name, kind, True))
        # any other instance (e.g. new Forever dungeons): no entry, the addon posts a summary
    out = [
        "-- Data/Dungeons.lua: final bosses that trigger a \"dungeon\" post on ENCOUNTER_END (success == 1).",
        f"-- GENERATED by scripts/gen_data.py from WoW Forever build {build} (DungeonEncounter + Map DB2).",
        "-- Do not edit by hand: change scripts/gen_data.py and run it again.",
        "--",
        "-- Encounter ids are the game's own. Only well-known final bosses (or a wing's final boss) are",
        "-- listed; for every other instance the addon posts a summary when you leave (Notifiers/Dungeon.lua).",
        "local _, ns = ...",
        "ns.Data = ns.Data or {}",
        "",
        "local list = {",
    ]
    for eid, boss, inst, kind, ver in entries:
        out.append(f"  {{ id = {eid}, boss = {lua_str(boss)}, instance = {lua_str(inst)}, kind = \"{kind}\" }},")
    out += [
        "}",
        "",
        "local byId, byName = {}, {}",
        "for _, e in ipairs(list) do",
        "  byId[e.id] = e",
        "  byName[e.boss:lower()] = byName[e.boss:lower()] or e",
        "end",
        "",
        f"ns.Data.Dungeons = {{ list = list, byId = byId, byName = byName, build = \"{build}\" }}",
        "",
        "-- Returns the table entry for a finished encounter, or nil if it is not a final boss.",
        "-- Matching is by id; the (English) name is only a fallback for ids missing from this table.",
        "function ns.Data.FindFinalBoss(encounterID, encounterName)",
        "  if encounterID and byId[encounterID] then return byId[encounterID] end",
        "  if type(encounterName) == \"string\" then return byName[encounterName:lower()] end",
        "  return nil",
        "end",
        "",
    ]
    return "\n".join(out), len(entries)


# ---------------------------------------------------------------------------------------------
# Legacy challenges = achievements in Forever's legacy categories (Classes, Tradeskills, Dungeons,
# Raids, Player vs. Player, Adventure and their sub-categories). "Hidden:" trackers are skipped.
# ---------------------------------------------------------------------------------------------
LEGACY_ROOTS = {"Classes", "Tradeskills", "Dungeons", "Raids", "Player vs. Player", "Adventure"}


def gen_legacy(build):
    cats = {r["ID"]: r for r in table("Achievement_Category", build)}

    def root(cid):
        while cid in cats and cats[cid]["Parent"] != "-1":
            cid = cats[cid]["Parent"]
        return cid

    roots = {cid for cid, c in cats.items() if c["Parent"] == "-1" and c["Name_lang"] in LEGACY_ROOTS}
    rows = []
    for a in table("Achievement", build):
        if root(a["Category"]) not in roots or a["Title_lang"].startswith("Hidden:"):
            continue
        sub = cats[a["Category"]]["Name_lang"]
        top = cats[root(a["Category"])]["Name_lang"]
        group = top if sub == top else f"{top}: {sub}"
        rows.append((int(a["ID"]), a["Title_lang"], group, a["Description_lang"]))
    rows.sort()
    out = [
        "-- Data/Legacy.lua: WoW Forever legacy challenges (achievement id -> name, group).",
        f"-- GENERATED by scripts/gen_data.py from WoW Forever build {build} (Achievement DB2).",
        "-- Do not edit by hand: change scripts/gen_data.py and run it again.",
        "-- zone = true marks single-zone \"Explore <zone>\" steps (posted only if settings.legacyZones).",
        "local _, ns = ...",
        "ns.Data = ns.Data or {}",
        "",
        "ns.Data.Legacy = {",
    ]
    for aid, title, group, desc in rows:
        zone = group.startswith("Adventure: ") and group != "Adventure: Explorer" and title.startswith("Explore ")
        out.append(f"  [{aid}] = {{ name = {lua_str(title)}, group = {lua_str(group)}"
                   f"{', zone = true' if zone else ''} }},")
    out += ["}", "", "-- legacy root categories: achievements earned in these (incl. sub-categories) that are not",
            "-- listed above (added by a later patch) are still posted, via GetAchievementCategory.",
            "ns.Data.LegacyRoots = {"]
    for cid in sorted(roots, key=int):
        out.append(f"  [{cid}] = {lua_str(cats[cid]['Name_lang'])},")
    out += ["}", f"ns.Data.LegacyBuild = \"{build}\"", ""]
    return "\n".join(out), len(rows)


def main():
    build = sys.argv[1] if len(sys.argv) > 1 else latest_build()
    for fname, gen in (("Dungeons.lua", gen_dungeons), ("Legacy.lua", gen_legacy)):
        text, n = gen(build)
        with open(f"{ROOT}/addon/NavtokDiscord/Data/{fname}", "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print(f"{fname}: {n} entries (build {build})")


if __name__ == "__main__":
    main()
